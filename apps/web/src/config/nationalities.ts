export function nationalityDisplay(code: string | null) {
  if (!code?.trim()) return { code: '?', label: '国籍未知', flagSrc: null }
  const historical = HISTORICAL_NATIONALITIES[code]
  if (historical) return { code, label: `历史国籍：${historical}（${code}）`, flagSrc: null }
  const flag = MODERN_FLAGS[code]
  return {
    code,
    label: flag
      ? `${NATIONALITY_NAMES[code] ?? code}（${code}）`
      : `国籍代码 ${code}，暂无核实旗帜`,
    flagSrc: flag ? `/flags/${flag}.svg` : null,
  }
}
